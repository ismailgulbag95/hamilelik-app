  /// Cinsiyete göre isimleri filtreler
  static List<BabyNameModel> getNamesForGender(String? gender) {
    if (gender == 'girl') {
      return allNames.where((n) => n.gender == 'girl' || n.gender == 'unisex').toList();
    } else if (gender == 'boy') {
      return allNames.where((n) => n.gender == 'boy' || n.gender == 'unisex').toList();
    }
    // 'surprise' veya belirtilmemişse hepsi
    return allNames;
  }

  /// Belirli bir tohum (seed) veya rastgele 5 isim seçer
  static List<BabyNameModel> pick5DailyNames({
    required String? gender,
    List<String> excludeNames = const [],
  }) {
    final pool = getNamesForGender(gender).where((n) => !excludeNames.contains(n.name)).toList();
    if (pool.length <= 5) {
      final fallbackPool = getNamesForGender(gender).toList();
      fallbackPool.shuffle();
      return fallbackPool.take(5).toList();
    }
    pool.shuffle();
    return pool.take(5).toList();
  }
